#!/usr/bin/env python3
"""Build the dependency-free ScaleBench profile and case browser."""

from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BUILD_MARKER = ".scalebench-viewer-build"


def prepare_output(output: Path) -> None:
    output = output.resolve()
    if output in {ROOT, ROOT.parent, Path("/")}:
        raise SystemExit(f"refusing unsafe output directory: {output}")
    if output.exists():
        marker = output / BUILD_MARKER
        if not marker.is_file():
            raise SystemExit(
                f"refusing to replace unmarked directory {output}; choose an empty path"
            )
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / BUILD_MARKER).write_text(
        "Generated by scripts/build_viewer.py; safe to replace.\n",
        encoding="utf-8",
    )


def validate_release(root: Path) -> list[dict]:
    manifest_path = root / "data" / "manifest.json"
    records = json.loads(manifest_path.read_text(encoding="utf-8"))
    if len(records) != 200:
        raise SystemExit(f"expected 200 cases, found {len(records)}")
    if [record["index"] for record in records] != list(range(200)):
        raise SystemExit("manifest case indices are not exactly 0..199")

    task_ids = []
    for record in records:
        task_id = record["task_id"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", task_id):
            raise SystemExit(f"invalid semantic task ID: {task_id}")
        if re.fullmatch(r"rtl[p]{2}_\d+", task_id, flags=re.IGNORECASE):
            raise SystemExit(f"source-corpus task ID cannot be public: {task_id}")
        if record["top_module"] != task_id:
            raise SystemExit(f"top-module mismatch for {task_id}")
        task_ids.append(task_id)
        for path_key in ("spec_path", "reference_path", "sec_tcl_path"):
            path = root / record[path_key]
            if not path.is_file():
                raise SystemExit(f"missing viewer source file: {record[path_key]}")
    if len(set(task_ids)) != 200:
        raise SystemExit("semantic task IDs are not unique")

    return records


def build(root: Path, output: Path) -> None:
    records = validate_release(root)
    prepare_output(output)

    shutil.copytree(root / "viewer", output, dirs_exist_ok=True)
    (output / ".nojekyll").write_text("", encoding="utf-8")

    data_output = output / "data"
    data_output.mkdir()
    shutil.copy2(root / "data" / "manifest.json", data_output / "manifest.json")
    shutil.copytree(root / "data" / "cases", data_output / "cases")

    sequential = sum(bool(record["is_sequential"]) for record in records)
    print(
        f"built benchmark site: cases={len(records)}, sequential={sequential}, "
        f"combinational={len(records) - sequential}, output={output.resolve()}"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, default=ROOT / "_site")
    args = parser.parse_args()
    build(args.root.resolve(), args.output.resolve())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
